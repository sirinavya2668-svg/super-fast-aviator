import { AsyncLocalStorage } from 'node:async_hooks';

// SQL strings are application-owned. Values always stay bound parameters.
export function postgresSql(source) {
  let sql = source.replace(/PRAGMA\s+[^;]+;/gi, '')
    .replace(/\bid INTEGER PRIMARY KEY\b/gi, 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bBLOB\b/gi, 'BYTEA')
    .replace(/\bREAL\b/gi, 'DOUBLE PRECISION')
    .replace(/\bCURRENT_TIMESTAMP\b/gi, "(to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))");
  if (/INSERT OR IGNORE/i.test(sql)) {
    sql = sql.replace(/INSERT OR IGNORE/i, 'INSERT').trim().replace(/;$/, '') + ' ON CONFLICT DO NOTHING';
  }
  let number = 0, quote = false;
  let result = '';
  for (let i = 0; i < sql.length; i++) {
    const ch = sql[i];
    if (ch === "'") {
      result += ch;
      if (quote && sql[i + 1] === "'") { result += sql[++i]; continue; }
      quote = !quote;
    } else if (ch === '?' && !quote) result += '$' + (++number);
    else result += ch;
  }
  return result;
}

export async function openDatabase() {
  if (process.env.SFA_TEST_SQLITE === '1') {
    if (process.env.NODE_ENV !== 'test') throw new Error('Test storage is disabled outside NODE_ENV=test.');
    return (await import('./test/async-sqlite.js')).openTestDatabase();
  }
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL is required. Set the Render PostgreSQL Internal Database URL; no local fallback is used.');
  }
  if (process.env.SFA_TEST_PGLITE && process.env.NODE_ENV !== 'test') throw new Error('Test PostgreSQL is disabled in production.');
  const {default: pg} = process.env.SFA_TEST_PGLITE === '1'
    ? await import('./test/pglite-pool.js')
    : await import('pg');
  pg.types.setTypeParser(20, value => {
    const n = Number(value);
    if (!Number.isSafeInteger(n)) throw new Error('Database integer exceeds the supported range.');
    return n;
  });
  const pool = new pg.Pool({
    connectionString: process.env.DATABASE_URL,
    max: 4,
    connectionTimeoutMillis: 10000,
    idleTimeoutMillis: 30000,
    statement_timeout: 15000,
    ...(process.env.DATABASE_SSL === 'true' ? {ssl:{rejectUnauthorized:true}} : {}),
  });
  pool.on('error', error => console.error('PostgreSQL connection error:', error.code || 'connection failed'));
  const context = new AsyncLocalStorage();
  let savepoint = 0;
  const rawQuery = (sql, params = []) => (context.getStore() || pool).query(sql, params);
  const query = (sql, params = []) => rawQuery(postgresSql(sql), params);
  const q = async (sql, ...params) => (await query(sql, params)).rows;
  const one = async (sql, ...params) => (await q(sql, ...params))[0];
  const run = async (source, ...params) => {
    let sql = source;
    const insert = /\bINSERT\s+(?:OR IGNORE\s+)?INTO\s+([a-z_]+)/i.exec(sql);
    if (insert && !['settings','sfa_runtime'].includes(insert[1].toLowerCase()) && !/\bRETURNING\b/i.test(sql)) {
      // Add RETURNING after the ON CONFLICT rewrite, where present.
      const result = await rawQuery(postgresSql(sql).trim().replace(/;$/, '') + ' RETURNING id', params);
      return {lastInsertRowid:result.rows[0]?.id, changes:result.rowCount};
    }
    const result = await query(sql, params);
    return {changes:result.rowCount};
  };
  const tx = async callback => {
    const nested = context.getStore();
    if (nested) {
      const name = 'sfa_savepoint_' + (++savepoint);
      await nested.query('SAVEPOINT ' + name);
      try { const result = await callback(); await nested.query('RELEASE SAVEPOINT ' + name); return result; }
      catch (error) { await nested.query('ROLLBACK TO SAVEPOINT ' + name); await nested.query('RELEASE SAVEPOINT ' + name); throw error; }
    }
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await context.run(client, callback);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK').catch(() => {});
      throw error;
    } finally { client.release(); }
  };
  const gameTransaction = callback => tx(async () => {
    // One shared lock also fences overlapping Render deployments.
    await query('SELECT pg_advisory_xact_lock(20261106, 7361)');
    return callback();
  });
  const db = {exec:async sql => {
    // Serialize schema additions during overlapping deployments.
    await tx(async () => {
      await query('SELECT pg_advisory_xact_lock(20261106, 7362)');
      await query(sql);
    });
  }};
  await pool.query('SELECT 1');
  await db.exec("CREATE TABLE IF NOT EXISTS sfa_runtime(key TEXT PRIMARY KEY, body TEXT NOT NULL)");
  return {db,q,one,run,tx,gameTransaction,closeDatabase:()=>pool.end()};
}
